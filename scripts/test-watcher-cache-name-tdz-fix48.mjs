import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const watcher = fs.readFileSync(path.join(ROOT, 'AUTO_PUBLISH_WATCHER.js'), 'utf8');
const publisher = fs.readFileSync(path.join(ROOT, 'ONECLICK_AKADEMIA.js'), 'utf8');
const contract = fs.readFileSync(path.join(ROOT, 'scripts/release-contract-fix49.cjs'), 'utf8');
const slice = (source, startText, endText) => { const a=source.indexOf(startText), b=source.indexOf(endText,a); assert.ok(a>=0&&b>a); return source.slice(a,b); };
const fn = slice(watcher, 'function verifyLocalRelease()', 'async function verifyPublishedRelease()');
assert.ok(fn.includes('readServiceWorkerContract(swPath)'), 'Watcher musi pobierać źródło i CACHE_NAME przez wspólny helper.');
const decl = fn.indexOf('const { source: sw, cacheName: swCacheName } = readServiceWorkerContract(swPath)');
assert.ok(decl >= 0, 'Brak jednego wspólnego odczytu SW/cache.');
assert.ok(fn.indexOf('swCacheName.includes(') > decl, 'swCacheName nie może być używane przed wspólną inicjalizacją.');
assert.ok(!fn.includes('const swCacheMatch =') && !fn.includes('const swCacheName = swCacheMatch'), 'Nie może wrócić rozproszony parser CACHE_NAME.');
assert.equal((contract.match(/\bconst\s+CACHE_NAME\s*=/g)||[]).length,0,'Helper nie może zawierać deklaracji cache Service Workera.');
assert.ok(contract.includes('readServiceWorkerContract') && contract.includes('dokładnie jedną deklarację CACHE_NAME'));
assert.ok(watcher.includes('test-watcher-cache-name-tdz-fix48.mjs'));
assert.ok(publisher.includes('test-watcher-cache-name-tdz-fix48.mjs'));
console.log('PASS FIX48/FIX49: watcher initializes SW and cache name together through the common manifest helper.');
