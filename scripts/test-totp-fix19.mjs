import assert from 'node:assert/strict';
import { totpCode, verifyTotp, encryptTotpSecret, decryptTotpSecret, generateTotpSecret, encodeBase32, decodeBase32, generateRecoveryCodes, hashRecoveryCode, totpChallengeCookie, readTotpChallengeCookie } from '../functions/_totp.js';

const rfcSecret = 'GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ';
assert.equal(await totpCode(rfcSecret, 59000), '287082', 'RFC 6238 / SHA1 vector 59s');
assert.equal(await totpCode(rfcSecret, 1111111109000), '081804', 'RFC 6238 / SHA1 vector 1111111109s');
const now = 1710000000000;
const current = await totpCode(rfcSecret, now);
assert.equal(await verifyTotp(rfcSecret, current, now), true);
assert.equal(await verifyTotp(rfcSecret, current, now + 30000), true, 'allow one-step clock drift');
assert.equal(await verifyTotp(rfcSecret, 'ABC123', now), false);
const secret = generateTotpSecret();
assert.equal(decodeBase32(encodeBase32(decodeBase32(secret))).length, 20, 'TOTP secret is 160-bit');
const env = { AUTH_TOTP_ENCRYPTION_KEY: Buffer.alloc(32, 0x5a).toString('base64') };
const sealed = await encryptTotpSecret(secret, env);
assert.notEqual(sealed.cipher, secret, 'stored secret must be ciphertext');
assert.equal(await decryptTotpSecret(sealed.cipher, sealed.iv, env), secret, 'AES-GCM round trip');
await assert.rejects(() => decryptTotpSecret(sealed.cipher, sealed.iv, { AUTH_TOTP_ENCRYPTION_KEY: Buffer.alloc(32, 0x11).toString('base64') }), 'wrong key must fail closed');
const codes = generateRecoveryCodes(10);
assert.equal(codes.length, 10);
assert.equal(new Set(codes).size, 10);
assert.ok(codes.every(code => /^[A-F0-9]{20}$/.test(code)));
assert.equal(await hashRecoveryCode(codes[0]), await hashRecoveryCode(codes[0].toLowerCase()), 'recovery code hash normalizes case');
assert.notEqual(await hashRecoveryCode(codes[0]), codes[0], 'only code hash is stored');
const cookie = totpChallengeCookie('test.challenge.token');
assert.match(cookie, /HttpOnly/); assert.match(cookie, /Secure/); assert.match(cookie, /SameSite=Lax/); assert.match(cookie, /Path=\/api\/auth\/totp\/verify/);
const request = new Request('https://example.test/api/auth/totp/verify', { headers:{ cookie:'other=x; '+cookie.split(';')[0] } });
assert.equal(readTotpChallengeCookie(request), 'test.challenge.token');
console.log('PASS: RFC 6238 TOTP vectors, ±30s window, AES-GCM at-rest encryption, invalid-key rejection, recovery codes, and HttpOnly SameSite=Lax challenge cookie for OAuth redirect compatibility.');
