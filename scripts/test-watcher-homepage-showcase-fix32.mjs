import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(import.meta.url);
const {verifyHomepageShowcase}=require(path.join(root,'scripts','homepage-showcase-guard.js'));
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('WEB_PUBLISH/index.html');
const js=read('WEB_PUBLISH/assets/homepage-showcase-640.js');
const css=read('WEB_PUBLISH/assets/homepage-showcase-640.css');
const result=verifyHomepageShowcase(html,js,css,root);
assert.deepEqual(result,{slides:6,uniqueIllustrations:6,uniqueVisualIds:36,hasLearningCenter:true,homepageImages:36,moduleCards:19,specialistCards:6,photoSlots:19,peopleAllowed:false});
const start=html.indexOf('id="view-home"'),end=html.indexOf('id="view-',start+20),home=html.slice(start,end>start?end:undefined);
const slideTags=[...home.matchAll(/<article\b[^>]*class="[^"]*\bnp640-slide[^"]*"[\s\S]*?<img\b([^>]*)>/gi)].map(m=>m[1]);
assert.equal(slideTags.length,6);
assert.ok(slideTags.every(x=>/data-photo-id="home-slide-/.test(x)&&/src="assets\/artwork-fix(?:77|51)\//.test(x)));
const badSource=html.replace('assets/artwork-fix77/slide-01.svg','https://example.invalid/person-photo.jpg');
assert.throws(()=>verifyHomepageShowcase(badSource,js,css,root),/brak zatwierdzonej lokalnej ilustracji awaryjnej/);
const noLock=html.replace('data-photo-eligible="false"','data-photo-eligible="true"');
assert.doesNotThrow(()=>verifyHomepageShowcase(noLock,js,css,root));
const watcher=read('AUTO_PUBLISH_WATCHER.js'),one=read('ONECLICK_AKADEMIA.js');
assert.ok(watcher.includes("require('./scripts/homepage-showcase-guard')"));
assert.ok(watcher.includes('verifyHomepageShowcase(html, homeShowcaseJs, homeShowcaseCss)'));
assert.ok(one.includes("require('./scripts/homepage-showcase-guard')"));
assert.ok(one.includes('verifyHomepageShowcase(indexHtml, homeShowcaseJs, homeShowcaseCss, ROOT)'));
console.log('[PASS] Watcher sprawdza 36 lokalnych grafik technicznych, 19 modułów, 6 slajdów i 6 specjalizacji; sloty zdjęć sprzętu są aktywne, a SVG pozostaje fallbackiem.');
console.log('FIX129 WATCHER HOMEPAGE SHOWCASE: 4/4 PASS');
