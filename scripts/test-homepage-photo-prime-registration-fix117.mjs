import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(ROOT,p),'utf8');
const release=JSON.parse(read('WEB_PUBLISH/release.json'));
const html=read('WEB_PUBLISH/index.html');
const prime=read('WEB_PUBLISH/assets/homepage-photo-prime-fix118.js');
const catalog=read('WEB_PUBLISH/assets/photo-catalog-fix115.js');
const tech=read('WEB_PUBLISH/assets/homepage-tech-only-fix122.js');
const start=html.indexOf('id="view-home"'),end=html.indexOf('id="view-',start+20),home=html.slice(start,end>start?end:undefined);
const tags=[...home.matchAll(/<img\b[^>]*>/gi)].map(m=>m[0]);
assert.equal(release.latestHotfix,'FIX128');
assert.equal(release.homepagePhotoFirstRenderFix?.hotfix,'FIX118');
assert.equal(release.homepagePhotoFirstRenderFix?.registeredAssignments,0);
assert.equal(release.homepagePhotoFirstRenderFix?.homepageEnabled,false);
assert.equal(tags.length,36);
assert.ok(tags.every(tag=>/data-photo-ignore="true"/.test(tag)&&/data-photo-eligible="false"/.test(tag)&&/src="assets\/artwork-fix(?:77|51)\/[^\"]+\.svg"/.test(tag)));
assert.ok(prime.includes('FIX122 homepage technical-visual lock'));
assert.ok(catalog.includes('FIX122: never register a people-photo seed for a homepage technical SVG slot'));
assert.ok(tech.includes('LOCKED_SOURCES')&&tech.includes('MutationObserver'));
console.log('[PASS] FIX118 homepage seed registration is retired by FIX122; 36 local technical SVG slots stay locked.');
