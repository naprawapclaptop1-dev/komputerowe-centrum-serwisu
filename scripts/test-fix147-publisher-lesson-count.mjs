#!/usr/bin/env node
'use strict';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const WEB=path.join(ROOT,'WEB_PUBLISH');
const read=(p)=>fs.readFileSync(path.join(ROOT,p),'utf8');
const html=read('WEB_PUBLISH/index.html');
const publisher=read('ONECLICK_AKADEMIA.js');
const watcher=read('AUTO_PUBLISH_WATCHER.js');
const sw=read('WEB_PUBLISH/service-worker.js');
const release=JSON.parse(read('WEB_PUBLISH/release.json'));
const expectedBuild='6.8.0-fix176-global-academy-rescue-and-master-launch-20261115';
const expectedCache='nauka-6.8.0-fix176-global-academy-rescue-and-master-launch-20261115';
const badge=html.match(/id=["']lessonTotalBadge["']>\s*(\d+)/i);
assert.ok(badge,'HTML must expose lessonTotalBadge');
assert.equal(Number(badge[1]),1083,'displayed lesson catalog must contain 1083 lessons');
assert.ok(html.includes('assets/academy-ultra-lessons-3.js'),'third historical training pack must remain loaded');
assert.ok(html.includes('content="FIX149"'),'HTML must identify active publisher hotfix');
assert.ok(publisher.includes("releaseJson.latestHotfix !== 'FIX176'"));
assert.ok(publisher.includes('fix149Extension.productVersion !== releaseVersion'));
assert.ok(!publisher.includes('fix149Extension.productVersion !== RELEASE')); 
assert.ok(publisher.includes(`releaseJson.latestHotfixBuild !== '${expectedBuild}'`));
assert.ok(publisher.includes('Number(lessonBadge[1]) !== 1083'));
assert.ok(publisher.includes('lessons:1083'));
assert.ok(watcher.includes("localRelease.latestHotfix !== 'FIX176'"));
assert.ok(watcher.includes('Number(badge[1]) !== 1083'));
assert.ok(watcher.includes("hasIdText('lessonTotalBadge', '1083')"));
assert.ok(watcher.includes('lessons: 1083'));
assert.ok(watcher.includes('1083 lekcje'));
assert.equal(release.release,'6.8.0');
assert.equal(release.latestHotfix,'FIX176');
assert.equal(release.latestHotfixBuild,expectedBuild);
assert.equal(release.serviceWorkerCacheName,expectedCache);
assert.equal(release.currentLessonCatalog.totalCatalogLessons,1083);
assert.equal(release.currentLessonCatalog.baselineBeforeFix145,1078);
assert.equal(release.currentLessonCatalog.addedByFix145,5);
assert.ok(release.features.includes('1083-practical-lessons'));
assert.ok(sw.includes(`const CACHE_NAME = '${expectedCache}'`));
assert.ok(!publisher.includes('Number(lessonBadge[1]) !== 1078'));
assert.ok(!watcher.includes("hasIdText('lessonTotalBadge', '1078')"));
// Load the actual lesson scripts and verify the final runtime total, not just metadata.
const require=createRequire(import.meta.url);
global.window=global;
global.document={getElementById(){return null;},addEventListener(){},querySelectorAll(){return [];}};
global.localStorage={getItem(){return null;},setItem(){}};
for(const f of ['academy-data.js','academy-expansion.js','academy-ultra-lessons.js','academy-ultra-lessons-2.js','academy-ultra-lessons-3.js','academy-ultimate-lessons-600.js','academy-master-lessons-610.js']) require(path.join(WEB,'assets',f));
require(path.join(WEB,'assets','academy-expanded-practice-fix136.js'));
require(path.join(WEB,'assets','academy-expanded-practice-fix145.js'));
assert.equal(global.ACADEMY_DATA.courseLessons.length,1083);
assert.equal(new Set(global.ACADEMY_DATA.courseLessons.map(x=>x.id)).size,1083);
console.log('[PASS] Publisher and Watcher expect 1083 lessons and the third training pack remains required.');
console.log('[PASS] FIX145 lesson baseline 1078 + 5 new lessons = 1083 runtime entries with unique IDs.');
console.log('[PASS] Lesson contract remains historically FIX149 while active HTML and PWA runtime advance to FIX175.');
console.log('FIX149 PUBLISHER LESSON COUNT CONTRACT: 3/3 PASS');
