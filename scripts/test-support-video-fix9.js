const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const web = path.join(root, 'WEB_PUBLISH');
const html = fs.readFileSync(path.join(web, 'index.html'), 'utf8');
const video = path.join(web, 'media/videos/akademia-dlaczego-warto-wspierac.mp4');
const vtt = fs.readFileSync(path.join(web, 'media/videos/akademia-dlaczego-warto-wspierac.vtt'), 'utf8');
const sw = fs.readFileSync(path.join(web, 'service-worker.js'), 'utf8');
const release = JSON.parse(fs.readFileSync(path.join(web, 'release.json'), 'utf8'));
const videoBlock = html.match(/<video class="support-video"[\s\S]*?<\/video>/i)?.[0] || '';
assert.ok(videoBlock, 'Support video element exists');
assert.match(videoBlock, /fix9-clean-video/, 'Video URL is versioned for cache busting');
assert.match(videoBlock, /<track[^>]+kind="captions"/i, 'Optional Polish captions remain available');
assert.doesNotMatch(videoBlock, /\bdefault(?:\s|>)/i, 'Captions are not forced over the video by default');
assert.ok(html.includes('support-video-caption-help'), 'Caption toggle hint is visible');
assert.ok(html.includes('support-video-transcript'), 'Accessible transcript is below the player');
assert.ok(!html.includes('Autorski montaż z materiałów szkoleniowych platformy. Film ma polską narrację i napisy.'), 'Old duplicate player/caption markup is removed');
assert.ok(fs.statSync(video).size > 1_000_000, 'New rebuilt MP4 is larger than the old 834 KB placeholder montage');
const header = Buffer.alloc(12);
const fd = fs.openSync(video, 'r');
fs.readSync(fd, header, 0, 12, 0);
fs.closeSync(fd);
assert.equal(header.toString('ascii', 4, 8), 'ftyp', 'MP4 container signature is valid');
assert.ok(vtt.startsWith('WEBVTT'), 'Captions file is valid VTT');
assert.ok(vtt.includes('Każda wpłata jest dobrowolna') && vtt.includes('Dziękujemy'), 'Narration captions include closing lines');
assert.ok(sw.includes(release.serviceWorkerCacheName) && sw.includes('/media/videos/akademia-dlaczego-warto-wspierac.mp4'), 'PWA cache contains support media in FIX17 namespace');
assert.equal(release.release,'6.8.0');
console.log('PASS: rebuilt support video MP4, six-scene visual version, optional captions, transcript, no duplicate/blank old player, and FIX17 PWA cache namespace.');
