#!/usr/bin/env node
'use strict';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const web = path.join(root, 'WEB_PUBLISH');
const html = fs.readFileSync(path.join(web, 'index.html'), 'utf8');
const sw = fs.readFileSync(path.join(web, 'service-worker.js'), 'utf8');
const uniqueness = fs.readFileSync(path.join(web, 'assets', 'photo-uniqueness-fix77.js'), 'utf8');
const imagePath = path.join(web, 'media', 'hero-usbc-power-delivery-fix142.jpg');
const tag = html.match(/<img\b[^>]*data-photo-id="home-hero-usbc-main"[^>]*>/)?.[0] || '';
assert.ok(tag, 'HERO USB-C image tag exists');
assert.match(tag, /src="media\/hero-usbc-power-delivery-fix142\.jpg"/, 'HERO points to bundled local JPEG');
assert.match(tag, /data-photo-kind="port"/, 'HERO category is port');
assert.match(tag, /data-photo-local-fallback="assets\/artwork-fix77\/hero-main\.svg"/, 'SVG fallback remains available');
assert.ok(fs.existsSync(imagePath), 'local JPEG exists in project');
const bytes = fs.readFileSync(imagePath);
assert.deepEqual([...bytes.subarray(0,3)], [0xff,0xd8,0xff], 'valid JPEG signature');
assert.ok(bytes.length > 50000, 'photo is not an empty placeholder');
assert.ok(sw.includes('/media/hero-usbc-power-delivery-fix142.jpg?v=6.8.0-fix142'), 'service worker precaches local HERO photo');
assert.ok(!tag.includes('/media/photos/usb-c-laptop-port.jpg'), 'broken remote proxy URL is no longer used by HERO');
assert.ok(uniqueness.includes("'media/hero-usbc-power-delivery-fix142.jpg'"), 'FIX77 global photo guard must allow the bundled FIX142 HERO photo instead of replacing it with SVG');
console.log('[PASS] FIX142 HERO uses a bundled local USB-C port photograph.');
console.log('[PASS] SVG fallback is preserved and photo is precached for offline use.');
console.log('[PASS] Broken remote /media/photos/usb-c-laptop-port.jpg request removed from HERO.');
console.log('[PASS] FIX77 global uniqueness guard allowlists the bundled FIX142 HERO photo.');
console.log('FIX142 USB-C HERO PHOTO: 4/4 PASS');
