import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(import.meta.url);
const {verifyFix51Release}=require('./release-contract-fix51.cjs');
const result=verifyFix51Release(ROOT);
assert.equal(result.build,'6.8.0-fix51-visual-academy-pro-20261105');
assert.equal(result.localPhotos,12);
assert.equal(result.localPosters,3);
assert.equal(result.illustrations,18);
assert.equal(result.visualAssets,33);
const rootManifest=JSON.parse(fs.readFileSync(path.join(ROOT,'FIX51_RELEASE_MANIFEST.json'),'utf8'));
const publicContract=JSON.parse(fs.readFileSync(path.join(ROOT,'WEB_PUBLISH/release-contract-fix51.json'),'utf8'));
assert.equal(rootManifest.visualAssetCount,33);
assert.equal(publicContract.localPosters.length,3);
assert.equal(publicContract.localPhotos.length,12);
assert.equal(publicContract.technicalIllustrations.length,18);
console.log(`PASS FIX51 release contract: ${result.build}; ${result.localPhotos} photos; ${result.illustrations} SVG illustrations; ${result.visualAssets} visual assets.`);
