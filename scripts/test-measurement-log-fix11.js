const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(__dirname + '/../WEB_PUBLISH/assets/measurement-log-640.js', 'utf8');
const context = { window: {}, document: { readyState: 'loading', addEventListener() {} }, TextEncoder, Date, Math, JSON, Array, Object, Set, Map, Error, Number, String, Blob, URL };
vm.runInNewContext(source, context);
const api = context.window.NP_MEASUREMENT_LOG;
assert(api, 'measurement log API exists');
const data = new Map();
const storage = { getItem: k => data.has(k) ? data.get(k) : null, setItem: (k,v) => data.set(k,String(v)), removeItem: k => data.delete(k) };
const common = { deviceType: 'Laptop', brand: 'Lenovo', model: 'ThinkPad T14 Gen 2', boardId: 'NM-Cxxx', revision: 'REV 1.0', point: 'PL301', mode: 'voltage', unit: 'V', powerState: 'powered', value: 19.1, refMin: 18.5, refMax: 20, reference: 'Dokumentacja serwisowa, strona 42', notes: 'Pomiar testowy' };
const a = api.add(storage, common);
assert.equal(api.classify(a), 'within-range');
assert.equal(api.load(storage).length, 1);
assert.throws(() => api.add(storage, { ...common, mode: 'resistance', unit: 'Ω', powerState: 'powered' }), /odłączonych i odizolowanych/);
assert.throws(() => api.add(storage, { ...common, refMin: 25, refMax: 10 }), /Zakres referencyjny/);
const b = api.add(storage, { ...common, id: 'second', mode: 'resistance', unit: 'Ω', powerState: 'isolated', value: 42, refMin: 0, refMax: 10, point: 'PL302' });
assert.equal(api.classify(b), 'outside-range');
assert.equal(api.csv(api.load(storage)).charCodeAt(0), 0xFEFF);
assert.match(api.csv(api.load(storage)), /ThinkPad T14 Gen 2/);
assert.equal(api.remove(storage, 'second').length, 1);
api.clear(storage);
assert.equal(api.load(storage).length, 0);
console.log('PASS | pomiary zapisują się lokalnie i są przypisane do modelu / Board ID / rewizji');
console.log('PASS | pomiar Ω/ciągłości/test diody wymaga odłączonych i odizolowanych źródeł zasilania');
console.log('PASS | zakres referencyjny waliduje wartości i nie zgaduje parametrów');
console.log('PASS | klasyfikacja w zakresie / poza zakresem / brak referencji');
console.log('PASS | CSV UTF-8 z nagłówkiem BOM, usuwanie wpisu i czyszczenie');
