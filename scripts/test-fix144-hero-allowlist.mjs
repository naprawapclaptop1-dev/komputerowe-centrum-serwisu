#!/usr/bin/env node
'use strict';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const html = read('WEB_PUBLISH/index.html');
const guard = read('WEB_PUBLISH/assets/photo-uniqueness-fix77.js');
const tag = html.match(/<img\b[^>]*data-photo-id="home-hero-usbc-main"[^>]*>/)?.[0] || '';
assert.ok(tag, 'dedicated USB-C HERO image exists');
assert.match(tag, /src="media\/hero-usbc-power-delivery-fix142\.jpg"/, 'HERO points to bundled local photo');
assert.match(guard, /'media\/hero-usbc-power-delivery-fix142\.jpg'/, 'FIX77 raster allowlist includes the exact bundled HERO file');
assert.match(guard, /if\(!ALLOWED\.has\(src\)\)\{fallback\(img\);continue;\}/, 'non-allowlisted raster photos still get the safety fallback');
assert.ok(fs.existsSync(path.join(root, 'WEB_PUBLISH/media/hero-usbc-power-delivery-fix142.jpg')), 'bundled photo exists');
console.log('[PASS] Dedicated USB-C HERO source is the bundled local JPEG.');
console.log('[PASS] FIX77 allowlist recognizes the new local HERO JPEG, preventing false fallback replacement.');
console.log('[PASS] Global duplicate protection remains active for all other raster images.');
console.log('FIX144 HERO ALLOWLIST: 3/3 PASS');
