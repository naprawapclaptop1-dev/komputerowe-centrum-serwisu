assert.equal(contract.valid, true, `Kontrakt FIX108 nie przechodzi: ${contract.missing.join(', ')}`);
assert.ok(one.includes("releaseJson.latestHotfix !== 'FIX111'"), 'OneClick musi odrzucać nieaktualne metadane FIX106.');
