const { evaluatePhotoCatalogPublicationContract } = require('./photo-catalog-publication-contract-fix106.cjs');
const verifyStart = one.indexOf('async function verifyWeb()');
const verifyEnd = one.indexOf('\nasync function main()', verifyStart);
assert.ok(verifyStart >= 0 && verifyEnd > verifyStart, 'Nie można wydzielić verifyWeb().');
const verifyBody = one.slice(verifyStart, verifyEnd);
const declaration = verifyBody.indexOf('const localRelease = releaseJson;');
const contractCall = verifyBody.indexOf('remoteRelease:localRelease');
assert.ok(declaration >= 0, 'verifyWeb() musi jawnie przypisać localRelease = releaseJson.');
assert.ok(contractCall > declaration, 'Bramka zdjęć musi używać localRelease dopiero po deklaracji.');
