import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = rel => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const watcher = read('AUTO_PUBLISH_WATCHER.js');
const oneclick = read('ONECLICK_AKADEMIA.js');
const release = JSON.parse(read('WEB_PUBLISH/release.json'));
const contractStart = watcher.indexOf('const localPhotoCatalogCheck = evaluatePhotoCatalogPublicationContractFix111({');
assert.ok(contractStart >= 0, 'Watcher musi wywoływać kontrakt publikacji zdjęć FIX111.');
const contractEnd = watcher.indexOf('});', contractStart);
assert.ok(contractEnd > contractStart, 'Nie znaleziono zamknięcia wywołania kontraktu FIX111.');
const contractCall = watcher.slice(contractStart, contractEnd + 3);
assert.ok(watcher.includes("const localRelease = JSON.parse(fs.readFileSync(path.join(WEB,'release.json'),'utf8'));") , 'Watcher musi odczytać lokalne release.json do localRelease.');
assert.ok(contractCall.includes('remoteRelease:localRelease,'), 'Watcher musi przekazać istniejący obiekt localRelease do walidatora.');
assert.ok(!contractCall.includes('localReleaseMetadata'), 'Wywołanie nie może używać niezdefiniowanej zmiennej localReleaseMetadata.');
assert.equal(release.latestHotfix, 'FIX111', 'FIX114 nie może zmieniać wersji runtime zdjęć.');
assert.equal(release.photoCatalogRuntimeBuildTag, '6.8.0-fix111-active-view-photo-queue-20261109');
assert.ok(oneclick.includes('const localRelease = releaseJson;'), 'OneClick zachowuje jawne wiązanie releaseJson do localRelease.');
assert.ok(oneclick.includes('remoteRelease:localRelease'), 'OneClick przekazuje obiekt localRelease do tego samego kontraktu.');
assert.ok(!/\blocalReleaseMetadata\b/.test(watcher), 'Watcher nie może zawierać żadnego odwołania do nieistniejącego localReleaseMetadata.');
assert.ok(watcher.startsWith('// NAUKA OD A DO Z — DLA WSZYSTKICH 6.8.0 FIX111'), 'Nagłówek Watchera musi zachować aktywny identyfikator runtime zdjęć FIX111.');
assert.ok(watcher.startsWith('// NAUKA OD A DO Z — DLA WSZYSTKICH 6.8.0 FIX111 PHOTO QUEUE + FIX110 PWA CACHE GUARD; FIX114'), 'Nagłówek musi deklarować FIX114 bez zastępowania prefiksu FIX111.');
console.log('[PASS] Watcher reads WEB_PUBLISH/release.json into localRelease before photo-contract validation.');
console.log('[PASS] FIX111 photo publication guard receives the defined localRelease object.');
console.log('[PASS] No undefined localReleaseMetadata identifier remains in AUTO_PUBLISH_WATCHER.js.');
console.log('[PASS] OneClick and Watcher pass the same local release contract without changing FIX111 metadata.');
console.log('[PASS] Watcher header preserves the FIX111 release-contract prefix and declares FIX114.');
console.log('FIX114 WATCHER RELEASE METADATA SCOPE: 5/5 PASS');
