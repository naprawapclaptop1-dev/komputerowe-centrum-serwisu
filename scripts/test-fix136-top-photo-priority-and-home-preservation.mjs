#!/usr/bin/env node
'use strict';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(ROOT,p),'utf8');
const json=p=>JSON.parse(read(p));
const html=read('WEB_PUBLISH/index.html');
const catalog=read('WEB_PUBLISH/assets/photo-catalog-fix115.js');
const prime=read('WEB_PUBLISH/assets/homepage-photo-prime-fix118.js');
const sw=read('WEB_PUBLISH/service-worker.js');
const release=json('WEB_PUBLISH/release.json');
const start=html.indexOf('<section class="view-section active" id="view-home"');
assert.ok(start>=0,'home view start');
const token=/<section\b[^>]*>|<\/section\s*>/gi; token.lastIndex=start;
let depth=0,end=-1,match;
while((match=token.exec(html))){ if(match[0].toLowerCase().startsWith('</section'))depth--; else depth++; if(depth===0){end=token.lastIndex;break;} }
assert.ok(end>start,'home view closes');
let homeHtml=html.slice(start,end);
// FIX176 preserves two explicit home launchers from FIX175 requested by the user.
// Remove only those approved blocks before hashing; every older home byte stays protected.
const launchBanner = /^        <section class="a168-home-launch"[\s\S]*?^        <\/section>\n/m;
const launchCard = /^            <button type="button" data-a168-launch="overview" class="u6-command-card a168-home-command-card">[\s\S]*?<\/button>\n/m;
assert.equal((homeHtml.match(launchBanner)||[]).length,1,'FIX175 home launch banner must occur exactly once');
assert.equal((homeHtml.match(launchCard)||[]).length,1,'FIX175 quick-access card must occur exactly once');
homeHtml=homeHtml.replace(launchBanner,'').replace(launchCard,'');
const homeHash=crypto.createHash('sha256').update(homeHtml).digest('hex');
assert.equal(homeHash,'e1fb02efce0776f206c88d9d268ab834a364ddc3b7602673cae29a5e70834e81','#view-home may differ only by the two explicit launchers for FIX168–FIX175; original content remains byte-identical');
assert.ok(catalog.includes("const HOME_PRIORITY_SELECTOR = '#view-home .np630-photo-hero img, #view-home .np640-slide.is-active > img';"));
assert.ok(!catalog.includes("#view-home .np30-module-photo img"));
assert.ok(!catalog.includes("#view-home .np75-specialist-photo img"));
assert.ok(catalog.includes("const slide = img.closest?.('.np640-slide');"));
assert.ok(catalog.includes("if (slide && !slide.classList.contains('is-active')) return false;"));
assert.ok(catalog.includes('if (!eligible(img)) { processed.delete(img); scheduled.delete(img); pendingRetryImages.delete(img); continue; }'));
assert.ok(catalog.includes("record.target?.matches?.('.np640-slide')"));
assert.ok(catalog.includes('if (viewChanged || slideChanged) scheduleActiveViewQueue();'));
assert.ok(prime.includes("const inHero = Boolean(img.closest('.np630-photo-hero'));"));
assert.ok(prime.includes("const activeSlide = Boolean(slide && slide.classList.contains('is-active'));"));
assert.ok(prime.includes("img.loading = topPriority ? 'eager' : 'lazy';"));
assert.ok(prime.includes("img.fetchPriority = topPriority ? 'high' : 'low';"));
assert.ok(html.includes('homepage-photo-prime-fix118.js?v=6.8.0-fix136'));
assert.ok(html.includes('photo-catalog-fix115.js?v=6.8.0-fix136'));
assert.ok(sw.includes("const CACHE_NAME = 'nauka-6.8.0-fix176-global-academy-rescue-and-master-launch-20261115'"));
assert.ok(sw.includes("const PHOTO_CACHE_NAME = 'academy-photo-library-fix135'"));
for(const asset of ['academy-expanded-practice-fix136.js?v=6.8.0-fix136','practice-quiz-fix136.css?v=6.8.0-fix136','learning-engine.js?v=6.8.0-fix136','photo-catalog-fix115.js?v=6.8.0-fix136','homepage-photo-prime-fix118.js?v=6.8.0-fix136']) assert.ok(sw.includes(asset),`PWA CORE includes ${asset}`);
const manifest=json('WEB_PUBLISH/media/photo-sources-online.json');
const library=json('WEB_PUBLISH/media/home-photo-library-fix118.json');
assert.equal(Object.keys(manifest.homepageSlotSeedMap).length,19);
assert.equal(new Set(Object.values(manifest.homepageSlotSeedMap)).size,19);
assert.equal(library.entries.length,19);
assert.equal(library.hotfix,'FIX135');
assert.equal(library.cacheName,'academy-photo-library-fix135');
assert.equal(release.release,'6.8.0');
assert.equal(release.latestHotfix,'FIX176');
assert.equal(release.latestHotfixBuild,'6.8.0-fix176-global-academy-rescue-and-master-launch-20261115');
assert.equal(release.fix136_top_photo_priority_practice_lessons.d1Migrations,false);
assert.equal(release.fix136_top_photo_priority_practice_lessons.photoCacheName,'academy-photo-library-fix135');
console.log('[PASS] Top queue contains only the 3 hero images and currently active carousel slide.');
console.log('[PASS] Inactive carousel slides are deferred and become eligible when activated.');
console.log('[PASS] Lower homepage cards keep their original 19/19 curated photo assignments and are lazy-loaded.');
console.log(`[PASS] Homepage structure is preserved; only the FIX142 HERO photo binding changed (SHA-256 ${homeHash}).`);
console.log('[PASS] PWA caches the new FIX136 assets and preserves the FIX135 offline photo cache.');
console.log('FIX136 HOME PRESERVATION + FIX176 CACHE ROTATION: 5/5 PASS');
