import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'FIX50_RELEASE_MANIFEST.json'), 'utf8'));
assert.equal(manifest.fix, 'FIX50');
assert.equal(manifest.build, '6.8.0-fix50-photo-reliability-20261105');
assert.equal(manifest.localPhotos.length, 12);
for (const photo of manifest.localPhotos) assert.ok(fs.statSync(path.join(ROOT, 'WEB_PUBLISH', photo)).size > 1000, `pusty plik ${photo}`);
assert.ok(fs.existsSync(path.join(ROOT, 'WEB_PUBLISH/release-contract-fix50.json')));
console.log(`PASS historyczny kontrakt FIX50 zachowany: ${manifest.localPhotos.length} zdjęć lokalnych; aktywne wydanie sprawdza osobny kontrakt FIX51.`);
