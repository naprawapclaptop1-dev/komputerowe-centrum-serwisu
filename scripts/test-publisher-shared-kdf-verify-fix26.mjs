import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { assertSharedPasswordKdfContract } = require('./password-kdf-contract-fix26.js');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const publisher = read('ONECLICK_AKADEMIA.js');
const watcher = read('AUTO_PUBLISH_WATCHER.js');
const accountApi = read('functions/api/session.js');
const kdf = read('functions/_password-kdf.js');
const reset = read('functions/api/auth/password/reset.js');
assert.equal(assertSharedPasswordKdfContract({ accountApi, kdfSource: kdf, resetApi: reset }, 'test'), true);
assert.ok(publisher.includes("require('./scripts/password-kdf-contract-fix26')"));
assert.ok(watcher.includes("require('./scripts/password-kdf-contract-fix26')"));
assert.ok(publisher.includes('assertSharedPasswordKdfContract({ accountApi: accountSessionRuntime'));
assert.ok(watcher.includes('assertSharedPasswordKdfContract({ accountApi: auth'));
// The account route must import the shared KDF; it must not contain the PBKDF2 algorithm itself.
assert.ok(accountApi.includes("from '../_password-kdf.js'"));
assert.doesNotMatch(accountApi, /name:\s*['"]PBKDF2['"]/);
assert.throws(() => assertSharedPasswordKdfContract({ accountApi: accountApi.replace("from '../_password-kdf.js'", "from '../missing-kdf.js'"), kdfSource: kdf, resetApi: reset }, 'mutated-test'), /_password-kdf\.js/);
assert.throws(() => assertSharedPasswordKdfContract({ accountApi, kdfSource: kdf.replace('PBKDF2_ITERATIONS = 100000', 'PBKDF2_ITERATIONS = 210000'), resetApi: reset }, 'mutated-test'), /100000|210000/);
const status = read('functions/api/auth/status.js');
const release = JSON.parse(read('WEB_PUBLISH/release.json'));
const html = read('WEB_PUBLISH/index.html');
const sw = read('WEB_PUBLISH/service-worker.js');
assert.equal(release.build, '6.8.0-fix51-visual-academy-pro-20261105');
assert.ok(status.includes(`const BUILD = '${release.build}'`));
assert.ok(html.includes(`content="${release.build}"`));
assert.ok(sw.includes('fix28-practice-academy-pwa') && sw.includes('support-video-clean-fix9'));
console.log('PASS: publisher and watcher accept the shared KDF imported by /api/session, and still enforce PBKDF2 100000 in the helper/reset path.');
console.log('PASS: stale inline-PBKDF2 requirement rejected as invalid; missing import and 210000 regression are detected.');
