import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
const ROOT=process.cwd(), WEB=path.join(ROOT,'WEB_PUBLISH'), AS=path.join(WEB,'assets');
const html=fs.readFileSync(path.join(WEB,'index.html'),'utf8');
const release=JSON.parse(fs.readFileSync(path.join(WEB,'release.json'),'utf8'));
const app=fs.readFileSync(path.join(AS,'app.js'),'utf8');
const art=fs.readFileSync(path.join(AS,'photo-unique-thumbnails-fix30.js'),'utf8');
const sw=fs.readFileSync(path.join(WEB,'service-worker.js'),'utf8');
