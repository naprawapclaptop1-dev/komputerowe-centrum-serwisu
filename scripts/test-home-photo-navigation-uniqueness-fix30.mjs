assert.ok(!html.includes("behavior: 'instant'"));
const ids=new Set([...html.matchAll(/\bid=["']([^"']+)["']/g)].map(m=>m[1]));
assert.equal(ids.size,[...html.matchAll(/\bid=["']([^"']+)["']/g)].length,'static HTML ids must remain unique');
const views=new Set([...html.matchAll(/<section[^>]*\bid=["']view-([^"']+)["']/g)].map(m=>m[1]));
const navTargets=[...html.matchAll(/(?:data-nav|data-view)=["']([^"']+)["']/g)].map(m=>m[1]);
const missing=[...new Set(navTargets.filter(x=>!views.has(x)))];
assert.deepEqual(missing,[],'every navigation button must target an existing view');
const locked=[...html.matchAll(/<img[^>]+data-photo-lock=["']([^"']+)["'][^>]+src=["']([^"']+)["']/g)].map(m=>({id:m[1],src:m[2]}));
assert.equal(locked.length,22,'hero + six slides + thirteen module thumbnails are locked');
assert.equal(new Set(locked.map(x=>x.id)).size,22,'photo locks must be unique');
assert.equal(new Set(locked.map(x=>x.src.split(/[?#]/)[0])).size,22,'all 22 home visuals must use different files');
const localPhotos=locked.filter(x=>/\.(?:jpg|jpeg|png|webp)$/i.test(x.src));
assert.equal(localPhotos.length,12,'home uses exactly twelve genuine local workshop photos');
const illustrations=locked.filter(x=>x.src.endsWith('.svg'));
assert.equal(illustrations.length,10,'technical module illustrations are not mislabeled as photos');
for(const x of locked){if(!/^https?:\/\//i.test(x.src)&&!x.src.startsWith('data:'))assert.ok(fs.existsSync(path.join(WEB,x.src)),'missing local image '+x.src);}
assert.ok(art.includes('gallery:')&&art.includes('long-video:')&&art.includes('np630-fallback='));
assert.ok(sw.includes('home-refresh-fix30.css')&&sw.includes('photo-unique-thumbnails-fix30.js')&&sw.includes('artwork-fix30'));
// Exercise allocator: static photos are reserved, every credited gallery image is unique, and overflow uses distinct SVGs.
const onlinePhotos=Array.from({length:12},(_,i)=>({id:`p${i}`,kind:'board',url:`https://images.pexels.com/photos/${1000+i}/photo.jpeg?auto=compress`,author:'author',page:'https://www.pexels.com/'}));
const fakeImgs=locked.map(x=>({getAttribute:n=>n==='src'?x.src:null,dataset:{}}));
const document={querySelectorAll:selector=>selector==='img[data-photo-lock]'?fakeImgs:[],addEventListener:()=>{}};
const api={onlinePhotos,kind:item=>item?.category||'board',dataUrl:()=>''};
const window={ACADEMY_ART:api};
const location={href:'https://academy.test/'};
vm.runInNewContext(art,{window,document,location,URL,encodeURIComponent,Map,Set,Array,String,Math,Number});
const gallery=onlinePhotos.map(p=>api.dataUrl({id:p.id,image:p.url,category:p.kind},`gallery:${p.id}`));
const clean=x=>{try{const u=new URL(x,'https://academy.test');u.hash='';u.search='';return u.href;}catch{return x;}};
