assert.ok(cards.every(x=>x.startsWith('data:image/svg+xml,')),'after the real-photo pool is reserved, use unique illustrations instead of repeating a photo');
assert.ok(window.NP_PHOTO_UNIQUENESS_FIX30,'photo allocator must expose its diagnostics');
console.log('PASS: FIX30 navigation bridge, all view targets, 22 unique home visual assets, 12 distinct photo gallery sources, 80 distinct dynamic illustrations, offline fallback and PWA cache.');
