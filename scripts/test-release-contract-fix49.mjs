import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import contract from './release-contract-fix49.cjs';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// FIX49 remains a preserved historical module; FIX50 has its own active release contract.
const manifest = contract.loadFix49Manifest(ROOT);
assert.equal(manifest.fix, 'FIX49');
for (const required of manifest.requiredFiles) assert.ok(fs.existsSync(path.join(ROOT, required)), `brak zachowanego pliku FIX49: ${required}`);
for (const asset of [manifest.assets.runtime, manifest.assets.styles]) assert.ok(fs.existsSync(path.join(ROOT, 'WEB_PUBLISH/assets', asset)), `brak historycznego assetu FIX49: ${asset}`);
const publicManifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'WEB_PUBLISH/release-contract-fix49.json'), 'utf8'));
assert.equal(publicManifest.build, manifest.build, 'publiczny manifest historyczny musi pozostać zgodny');
const publisher = fs.readFileSync(path.join(ROOT, 'ONECLICK_AKADEMIA.js'), 'utf8');
const watcher = fs.readFileSync(path.join(ROOT, 'AUTO_PUBLISH_WATCHER.js'), 'utf8');
assert.ok(publisher.includes('verifyFix50Release(ROOT)'));
assert.ok(watcher.includes('verifyFix50Release(ROOT)'));
assert.ok(publisher.includes('runLocalNodeScript'));
assert.ok(watcher.includes('runFix49NodePreflight'));
console.log('PASS FIX49 legacy contract preserved; active publication is guarded by FIX50 contract.');
