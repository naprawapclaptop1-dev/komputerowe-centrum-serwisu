const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const file = __dirname + '/../WEB_PUBLISH/assets/progress-backup-621.js';
const context = { window: {}, document: { readyState: 'loading', addEventListener() {} }, TextEncoder, Date, JSON, Array, Object, Set, Map, Error };
vm.runInNewContext(fs.readFileSync(file, 'utf8'), context);
const api = context.window.NP_PROGRESS_BACKUP;
assert(api, 'API backup exists');
const store = () => { const data = new Map(); return { getItem: k => data.has(k) ? data.get(k) : null, setItem(k,v) { data.set(k,String(v)); }, removeItem: k => data.delete(k), data }; };
const a = store();
a.setItem('academyCompletedLessons', JSON.stringify(['L1','L2']));
a.setItem('academyGuideSteps', JSON.stringify({ A: { 0: true } }));
a.setItem('academyMeasurementLog', JSON.stringify([{ id: 'm1', model: 'Test PC' }]));
a.setItem('authToken', 'SECRET');
const backup = api.makeBackup(a, '2026-11-02T12:00:00.000Z');
assert.deepStrictEqual(Object.keys(backup.progress).sort(), ['academyCompletedLessons','academyGuideSteps','academyMeasurementLog'].sort());
const b = store();
b.setItem('academyCompletedLessons', JSON.stringify(['L2','L3']));
b.setItem('academyGuideSteps', JSON.stringify({ A: { 1: true }, B: { 0: true } }));
const changed = api.importBackup(b, JSON.stringify(backup));
assert(changed.includes('academyCompletedLessons'));
assert(changed.includes('academyMeasurementLog'));
assert.deepStrictEqual(JSON.parse(b.getItem('academyMeasurementLog')), [{ id: 'm1', model: 'Test PC' }]);
assert.deepStrictEqual(JSON.parse(b.getItem('academyCompletedLessons')), ['L2','L3','L1']);
assert.deepStrictEqual(JSON.parse(b.getItem('academyGuideSteps')), { A: { 1: true, 0: true }, B: { 0: true } });
assert.throws(() => api.parseBackup('{bad json'));
assert.throws(() => api.parseBackup({ schema: 'wrong', schemaVersion: 1, progress: { academyCompletedLessons: [] } }));
assert.throws(() => api.parseBackup({ schema: api.schema, schemaVersion: 1, progress: { academyCompletedLessons: {} } }));
const unknown = api.parseBackup({ schema: api.schema, schemaVersion: 1, progress: { authToken: 'SECRET', academyLanguage: 'pl' } });
assert.deepStrictEqual(Object.keys(unknown.progress), ['academyLanguage']);
// Simulate a one-time quota failure and verify rollback restores earlier data.
const rollbackStore = store();
rollbackStore.setItem('academyCompletedLessons', JSON.stringify(['OLD']));
rollbackStore.setItem('academyGuideSteps', JSON.stringify({ keep: true }));
const oldGuide = rollbackStore.getItem('academyGuideSteps');
const originalSet = rollbackStore.setItem; let failOnce = true;
rollbackStore.setItem = (key, value) => { if (key === 'academyGuideSteps' && failOnce) { failOnce = false; throw new Error('quota'); } originalSet(key, value); };
assert.throws(() => api.importBackup(rollbackStore, JSON.stringify(backup)));
assert.deepStrictEqual(JSON.parse(rollbackStore.getItem('academyCompletedLessons')), ['OLD']);
assert.strictEqual(rollbackStore.getItem('academyGuideSteps'), oldGuide);
console.log('PASS | import rollback restores old values after storage error');
console.log('PASS | export whitelist excludes auth token');
console.log('PASS | import merges arrays without duplicates');
console.log('PASS | import merges nested progress objects');
console.log('PASS | invalid JSON, schema and data types rejected');
console.log('PASS | unknown keys ignored');
console.log('PASS | ' + api.allowedKeys.length + ' allow-listed learning-data keys');
